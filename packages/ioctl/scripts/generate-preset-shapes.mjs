// Generates src/pages/pptx/presetShapes.ts from presetShapeDefinitions.xml,
// the DrawingML preset shape definitions published with ECMA-376 (the same
// file LibreOffice uses: oox/source/drawingml/customshapes/presetShapeDefinitions.xml).
//
// Usage: node scripts/generate-preset-shapes.mjs path/to/presetShapeDefinitions.xml
import fs from 'fs';

const xml = fs.readFileSync(process.argv[2], 'utf8');
const attr = (tag, name) => tag.match(new RegExp(`\\b${name}="([^"]*)"`))?.[1];

const shapes = {};
// Each shape is a top-level element of <presetShapeDefinitons>
for (const [, name, body] of xml.matchAll(/^ {2}<(\w+)>([\s\S]*?)^ {2}<\/\1>/gm)) {
  const guides = (list) => [...(body.match(new RegExp(`<${list}[^>]*>([\\s\\S]*?)</${list}>`))?.[1] ?? '').matchAll(/<gd [^>]*\/>/g)].map(([tag]) => `${attr(tag, 'name')}=${attr(tag, 'fmla')}`);
  const shape = { av: guides('avLst').join(';'), gd: guides('gdLst').join(';') };
  const rect = body.match(/<rect [^>]*\/>/)?.[0];
  if (rect) shape.rect = ['l', 't', 'r', 'b'].map((k) => attr(rect, k)).join(' ');
  shape.paths = [...body.matchAll(/<path( [^>]*)?>([\s\S]*?)<\/path>/g)].map(([, attrs = '', commands]) => {
    const path = {};
    for (const key of ['w', 'h', 'fill', 'stroke']) {
      const value = attr(attrs, key);
      if (value !== undefined) path[key] = key === 'w' || key === 'h' ? Number(value) : value;
    }
    const d = [];
    for (const [, command, content] of commands.matchAll(/<(moveTo|lnTo|arcTo|cubicBezTo|quadBezTo|close)\b([^>]*\/>|[\s\S]*?<\/\1>)/g)) {
      const points = [...content.matchAll(/<pt [^>]*\/>/g)].flatMap(([pt]) => [attr(pt, 'x'), attr(pt, 'y')]);
      if (command === 'arcTo') d.push('A', ...['wR', 'hR', 'stAng', 'swAng'].map((k) => attr(content, k)));
      else if (command === 'close') d.push('Z');
      else d.push({ moveTo: 'M', lnTo: 'L', cubicBezTo: 'C', quadBezTo: 'Q' }[command], ...points);
    }
    path.d = d.join(' ');
    return path;
  });
  shapes[name] = shape;
}

const header = `// Generated by scripts/generate-preset-shapes.mjs from presetShapeDefinitions.xml,
// part of ECMA-376 (Office Open XML File Formats), Part 1. Do not edit.
//
// Copyright © Ecma International. This document may be copied, published and
// distributed to others, and certain derivative works of it may be prepared,
// copied, published, and distributed, in whole or in part, provided that the
// above copyright notice and this Copyright License and Disclaimer are included
// on all such copies and derivative works. This document and the information
// contained herein is provided on an "AS IS" basis and ECMA INTERNATIONAL
// DISCLAIMS ALL WARRANTIES, EXPRESS OR IMPLIED, INCLUDING BUT NOT LIMITED TO ANY
// WARRANTY THAT THE USE OF THE INFORMATION HEREIN WILL NOT INFRINGE ANY
// OWNERSHIP RIGHTS OR ANY IMPLIED WARRANTIES OF MERCHANTABILITY OR FITNESS FOR
// A PARTICULAR PURPOSE.
//
// Each shape has its adjust values (av) and guides (gd) as "name=formula"
// lists, its text rectangle, and its paths with commands as M/L/A/C/Q/Z tokens.

export interface PresetPath {
  w?: number;
  h?: number;
  fill?: string;
  stroke?: string;
  d: string;
}

export interface PresetShape {
  av: string;
  gd: string;
  rect?: string;
  paths: PresetPath[];
}

`;
fs.writeFileSync(
  new URL('../src/pages/pptx/presetShapes.ts', import.meta.url),
  `${header}export const PRESET_SHAPES: Record<string, PresetShape> = ${JSON.stringify(shapes, null, 1)};\n`
);
console.log(`${Object.keys(shapes).length} shapes`);
